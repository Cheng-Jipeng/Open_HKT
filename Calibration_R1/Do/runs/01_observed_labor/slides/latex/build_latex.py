def put(body, x, y, w, size=15.2, color='ink', bold=False):
    style = r'\bfseries' if bold else ''
    parts.append(r'\node[anchor=north west,inner sep=0pt,outer sep=0pt,align=left,text width=' + f'{w}cm,'
                 + r'text=' + color + r',font=\sffamily\fontsize{' + str(size) + '}{' + str(size*1.23)
                 + r'}\selectfont' + style + '] at (' + f'{x}cm,{-y}cm' + ') {' + body + '};\n')


def start(title, phase, context, takeaway, foot=None, warning=False):
    global page
    page += 1
    parts.append(f'\n% ================ SLIDE {page:02d}: {title} ================\n')
    parts.extend('% Source note: ' + line + '\n' for line in notes[page-1].splitlines())
    parts.append(r'\begin{frame}[plain]' + '\n' + r'\begin{tikzpicture}[remember picture,overlay]' + '\n'
                 + r'\begin{scope}[shift={(current page.north west)}]' + '\n')
    put(phase.upper(),1.2,.6,29.6,11.5,'blue',True)
    put(title,1.2,1.5,29.6,26.5,'ink',True)
    put(context,1.2,3.05,29.6,13.2,'gray')
    put(takeaway,1.2,15.65,29.6,15.7,'red' if warning else 'blue',True)
    if foot is None:
        foot = r'Source: saved Calibration R1 outputs. Detailed mappings and equations are preserved in the \LaTeX{} source notes.'
    put(foot,1.2,17.15,28.0,9.6,'gray')
    put(f'{page:02d}',30.4,17.15,.7,9.6,'gray')


def end():
    parts.append(r'\end{scope}\end{tikzpicture}\end{frame}'+'\n')


def block(label, body, y, color='ink', size=15.2):
    put(label.upper(),1.2,y,9.1,10.8,'gray',True)
    put(body,1.2,y+.64,9.1,size,color)


def eq(body,y=12.75,size=15.5):
    put(body,1.2,y,9.3,size,'blue')


def constant(v): return [v]*len(years)
def scaled(a,v): return [v*x for x in a]
def index(a): return [100*x/a[0] for x in a]
def fmt(x,d=6): return f'{x:.{d}f}'
def pct(x,d=2): return f'{100*x:.{d}f}'+r'\%'


def ser(label, values, color='blue', dash=False, x=None, marker=False, points=False):
    return dict(label=label,values=values,color=color,dash=dash,x=years if x is None else x,
                marker=marker,points=points)


def plot(title, series, x=11.0,y=4.55,w=9.8,h=10.4,unit='',yrange=None,yticks=None,
         xrange=(2009,2024),xticks=(2009,2012,2015,2018,2021,2024),precision=1,xlabel=None):
    """Place a native axis rectangle and explicit legends in slide centimeters."""
    global chart_count
    chart_count += 1
    compact = h < 6
    title_size = 14.7 if not compact else 14
    put(title,x+.45,y,w-.55,title_size,'ink',True)
    # Axis bounds are specified directly; text and legends do not shrink the plot.
    ax_x = x+1.65
    ax_y = y + (h-2.4 if not compact else h-1.25)
    ax_h = h-4.0 if not compact else h-2.4
    ax_w = w-2.1
    options = [f'runplot,at={{({ax_x}cm,{-ax_y}cm)}},anchor=south west',
               f'width={ax_w}cm,height={ax_h}cm',f'xmin={xrange[0]},xmax={xrange[1]}',
               'xtick={'+','.join(str(t) for t in xticks)+'}',
               'yticklabel style={/pgf/number format/fixed,/pgf/number format/precision='+str(precision)+'}']
    if yrange is not None: options += [f'ymin={yrange[0]},ymax={yrange[1]}']
    if yticks is not None: options += ['ytick={'+','.join(str(t) for t in yticks)+'}']
    if unit: options += ['ylabel={'+unit+'}']
    if xlabel: options += ['xlabel={'+xlabel+'}']
    parts.append('\\begin{axis}['+','.join(options)+']\n')
    for v in series:
        assert len(v['x'])==len(v['values'])
        style = v['color'] + ',line width=1.35pt,' + ('dashed,' if v['dash'] else '')
        style += 'only marks,mark=*,mark size=1.8pt' if v['points'] else ('mark=*,mark size=1.3pt' if v['marker'] else 'mark=none')
        coords=' '.join(f'({float(a):.15g},{float(b):.15g})' for a,b in zip(v['x'],v['values']))
        parts.append(r'\addplot['+style+'] coordinates {'+coords+'};\n')
    parts.append('\\end{axis}\n')
    legend_y=y+h-1.2 if not compact else y+h-.5
    # Short stacked legends are readable and avoid panel-dependent auto wrapping.
    for k,v in enumerate(series):
        ly=legend_y+.49*k
        if compact:
            lx=x+1.1+k*4.1; ly=legend_y
        else: lx=x+1.2
        dash=',dashed' if v['dash'] else ''
        if v['points']:
            parts.append(r'\fill['+v['color']+f'] ({lx+.28}cm,{-ly-.14}cm) circle (1.7pt);\n')
        else:
            parts.append(r'\draw['+v['color']+',line width=1.3pt'+dash+f'] ({lx}cm,{-ly-.14}cm) -- ({lx+.58}cm,{-ly-.14}cm);\n')
        put(v['label'],lx+.75,ly-.04,w-1.95,11.4)
    chart_manifest.append(dict(slide=page,title=title,series=[dict(label=v['label'],x=v['x'],values=v['values']) for v in series]))


def table(headers,rows,widths,y=4.55,size=14.5,rowstretch=1.58):
    spec='@{}'+''.join('L{'+str(v)+'cm}' for v in widths)+'@{}'
    body=r'{\setlength{\tabcolsep}{7pt}\renewcommand{\arraystretch}{'+str(rowstretch)+'}'
    body+=r'\begin{tabular}{'+spec+r'}\toprule\color{blue}\bfseries '
    body+=(r' & \color{blue}\bfseries ').join(headers)+r'\\\midrule'+'\n'
    body+='\n'.join(' & '.join(row)+r'\\' for row in rows)
    body+=r'\bottomrule\end{tabular}}'
    put(body,11.0,y,19.8,size)


